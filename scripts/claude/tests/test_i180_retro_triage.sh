#!/bin/bash
# I180 決定論ゲート: retro SKILL.md の手順 2.7（改善案の要否判定）の文言・位置と、手順 3 の選定基準への追記を検証
set -u
SKILL="${I180_TEST_SKILL:-.claude/skills/retro/SKILL.md}"
NG=0
req() {
  if grep -Fq -- "$1" "$SKILL"; then echo "OK: $2"; else echo "NG: $2"; NG=$((NG+1)); fi
}
req "2.7) 改善案ごとに「本当に対応すべきか」を判定する" "T1 手順 2.7 の見出し"
req "ハーネス・ループエンジニアリングのベストプラクティス" "T2 基準 1（ベストプラクティス）"
req "足す工程が毎回のイシューにかけるコストと、それで防げる損失を比べる" "T3 基準 2（スピード）"
req "実害（手戻り・見逃し・障害）が本当に出たか" "T4 問 1（実害）"
req "その場で捕まったのではないか" "T5 問 2（既存の流れで捕捉）"
req "決定論のチェックを直せば足りるのではないか" "T6 問 3（決定論チェック優先）"
req "既存のイシュー（未着手のものを含む）に同梱できないか" "T7 問 4（既存イシュー同梱）"
req "このイシューで直す（記録の場所だけで済むもの）／既存イシューに同梱／採用（新規起票）／見送り" "T8 4 区分（I193: このイシューで直すを追加）"
req "新規起票は「実害があり、同梱先が無い」ものに限る" "T9 新規起票の条件"
req "見送りにしたものも理由とともに記録する" "T10 見送り理由の記録（I193: close でまとめて報告）"
req "手順 2.7 で「採用（新規起票）」または「既存イシューに同梱」と判定したものだけを" "T11 手順 3 の選定基準への追記"
req "手順3 と close 段階の報告" "T12 平易化ルールの適用場面（I193: 報告は手順 3 と close 段階）"
# T13: 手順 2.7 が 2.5 と 3 の間にある（行番号の順序）
l25=$(grep -n '^2\.5) ' "$SKILL" | head -1 | cut -d: -f1)
l27=$(grep -n '^2\.7) ' "$SKILL" | head -1 | cut -d: -f1)
l3=$(grep -n '^3) ' "$SKILL" | head -1 | cut -d: -f1)
if [ -n "$l25" ] && [ -n "$l27" ] && [ -n "$l3" ] && [ "$l25" -lt "$l27" ] && [ "$l27" -lt "$l3" ]; then
  echo "OK: T13 手順 2.7 が 2.5 と 3 の間"
else
  echo "NG: T13 手順 2.7 の位置（2.5=${l25:-なし} 2.7=${l27:-なし} 3=${l3:-なし}）"
  NG=$((NG+1))
fi

if [ "$NG" -gt 0 ]; then
  echo "RESULT: NG ($NG 件)"
  exit 1
fi
echo "RESULT: OK (13/13)"
