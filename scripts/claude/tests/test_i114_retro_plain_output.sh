#!/bin/bash
# I114 決定論ゲート: retro SKILL.md の平易化ルール文言の存在＋既存詳細フォーマットの維持を検証
set -u
SKILL="${I114_TEST_SKILL:-.claude/skills/retro/SKILL.md}"
NG=0
req() {
  if grep -Fq -- "$1" "$SKILL"; then echo "OK: $2"; else echo "NG: $2"; NG=$((NG+1)); fi
}
# G系: I114 で追加する平易化ルール文言
req "平易版を先に提示し、その後に詳細版" "G1 提示順（平易版→詳細版の併記）"
req "平易な言葉に置換する（省略ではない）" "G2 置換原則（省略ではない）"
req "過度な要約で情報を削らない" "G3 経緯・理由の保持"
req "詳細フォーマットを維持" "G4 記録は詳細維持"
req "本スキルへの記録ファイル新設はしない" "G5 記録ファイル新設なし"
req "経過（Why の連鎖）の提示を維持" "G6 5 Whys 経過維持・用語のみ平易化"
req "平易化の対象外" "G7 コマンド名・選択肢記号は対象外"
req "変換前" "G8 文例（変換前）"
req "変換後" "G9 文例（変換後）"
req "平易版 → 詳細版の順で併記" "G10 手順3 の併記指示"
# R系: 既存詳細フォーマット・分析手続きの維持（無改変検証）
req "| # | カテゴリ | 根本原因 | 対処内容 |" "R1 是正処置の詳細表ヘッダ維持"
req "| # | カテゴリ | 根本原因 | 予防策 | 対象ファイル |" "R2 予防処置の詳細表ヘッダ維持"
req "5 Whys の実施（最低 3 回）" "R3 5 Whys 内部手続き維持"
req "**承認ゲート**" "R4 手順5 承認ゲート維持"

if [ "$NG" -gt 0 ]; then
  echo "RESULT: NG ($NG 件)"
  exit 1
fi
echo "RESULT: OK (14/14)"
